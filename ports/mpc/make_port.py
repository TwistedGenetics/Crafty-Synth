def run(*cmd, **kw):
    r = subprocess.run([str(c) for c in cmd], cwd=REPO, capture_output=True, text=True, **kw)
    if r.returncode:
        sys.exit(f"make_port: {' '.join(map(str, cmd))} failed:\n{r.stdout}{r.stderr}")
    return r.stdout


PREFIXES = ("FILT EG ", "AMP EG ", "MOD EG ", "LFO 1 ", "LFO 2 ", "FILTER ", "OSC B ", "OSC ", "DELAY ", "REVERB ", "ARP ")


def short(name):
    """a control's on-screen name: without the page its frame's title already gives ("FILT EG ATTACK" -> "ATTACK")"""
    for p in PREFIXES:
        if name.startswith(p) and len(name) > len(p):
            return name[len(p):]
    return name


def bigger(layout, names):
    """the auto-layout's controls with larger names and values (the MPC's screen at arm's length), and every list a
    pop-up (the auto-layout's button stacks cut long choices like FM FROM A short)"""
    out = []
    for ln in layout.splitlines():
        k = re.search(r" key=(\S+)", ln)
        if k and k[1] in names and " label=" in ln:
            ln = re.sub(r' label="[^"]*"', f' label="{short(names[k[1]])}"', ln)
        m = re.match(r"(\s*)enum_[vh] cx=(\d+) cy=(\d+) (label=\"[^\"]*\") (key=\S+)", ln)
        if m:
            ln = f"{m[1]}popup cx={m[2]} cy={int(m[3]) - 18} w=134 h=48 {m[4]} {m[5]}"
        if re.match(r"\s*(knob|popup|enum_v|enum_h|toggle)\b", ln):
            if re.match(r"\s*knob\b", ln) and " vs=" not in ln:
                ln += " ns=17 vs=19"
            if re.match(r"\s*popup\b", ln) and " tsize=" not in ln:
                ln += " tsize=18"
        out.append(ln)
    return align_popups(out)


def align_popups(lines):
    """every pop-up on its row: 20 px under the nearest knob centre in its frame, as the auto-layout's own pop-ups"""
    frames, cur = [], None
    for i, ln in enumerate(lines):
        if ln.startswith("frame ") or ln.startswith("[tab"):
            cur = {"knobs": [], "popups": []}
            frames.append(cur)
        elif cur is not None:
            m = re.search(r" cy=(\d+)", ln)
            if m and ln.lstrip().startswith("knob "):
                cur["knobs"].append(int(m[1]))
            elif m and ln.lstrip().startswith("popup "):
                cur["popups"].append((i, int(m[1])))
    for f in frames:
        for i, cy in f["popups"]:
            if f["knobs"]:
                k = min(f["knobs"], key=lambda c: abs(c + 20 - cy))
                if abs(k + 20 - cy) <= 60:
                    lines[i] = re.sub(r" cy=\d+", f" cy={k + 20}", lines[i], count=1)
    return "\n".join(lines) + "\n"


def locked_order(params):
    """params.json's parameters in params.lock's order (the VST's index: saved projects bind by it), new keys after
    it: an engine parameter appended later lands after the port's own (table files, random) instead of before"""
    lock = (PORT / "params.lock").read_text().split() if (PORT / "params.lock").exists() else []
    head, rest = params.split('"params": [\n', 1)
    body, tail = rest.split("\n ],\n", 1)
    lines = [ln.rstrip(",") for ln in body.split("\n")]
    keyof = {json.loads(ln)["key"]: ln for ln in lines}
    order = [k for k in lock if k in keyof] + [json.loads(ln)["key"] for ln in lines if json.loads(ln)["key"] not in lock]
    return head + '"params": [\n' + ",\n".join(keyof[k] for k in order) + "\n ],\n" + tail


# the OSC page, as the editor's two OSC panels: badge, name and BANK on top, the 3D wavetable view (a filmstrip per
# factory bank on WT POS, shown while the engine's w<n>shown says that bank plays; a user bank or file shows
# art/wt_user.png), then two rows of controls in the editor's cells
OSC_SECTIONS = ("OSC A", "OSC B")
VIEW_W, VIEW_H = 560, 180
VIEW_COLS = 56
# per oscillator: its controls in two rows of up to four (None: an empty place), and its Q-Link columns: the
# WAVETABLE box with the first row, then the second row (each column a neat box around what it turns)
OSC = (
    ("A", 1, [("knob", "w1pos", "WT POS"), ("knob", "omamt", "OSC MOD"), ("popup", "ommode", "MOD MODE"), None,
              ("knob", "mix", "MIX"), ("knob", "spread", "SPREAD"), ("knob", "glide", "GLIDE"), ("knob", "oct", "OCTAVE")], 8),
    ("B", 2, [("knob", "w2pos", "WT POS"), ("knob", "bamt", "B MOD"), ("popup", "bmode", "B MODE"), None,
              ("knob", "tune", "TUNE"), ("knob", "fine", "FINE"), ("popup", "voices", "VOICES"), None], 9),
)
LIST_ROWS, ROW_H = 8, 68


def cells_svg(boxes):
    """the editor's control cells (.knob / .pick: a darker rounded box) behind a page's controls"""
    r = "".join(f'<rect x="{x}" y="{y}" width="{w}" height="{h}" rx="6" fill="#14171b" stroke="#343a42"/>'
                for x, y, w, h in boxes)
    # drawn over the plugin area (1280 x 628, from y = 86 of the layout's coordinates)
    return f'<svg xmlns="http://www.w3.org/2000/svg" width="1280" height="628" viewBox="0 86 1280 628">{r}</svg>\n'


# the MPC's tab bar: one short word a page (the long section names ran together on the MPC's buttons)
TAB_NAMES = {"SUB OSC / FILTER": "FILTER", "FILTER EG / AMP EG": "ENVELOPE", "MOD EG / LFO 1 / LFO 2": "MOD",
             "MATRIX LFO 1 - NOTE +1": "MATRIX", "REVERB / DELAY / MOD FX": "FX", "CRUSH / PRESET / ARP-SEQ": "PRESET",
             "CRUSH / PRESET": "PRESET", "ARP-SEQ": "ARP"}


def short_tabs(layout):
    for old, new in TAB_NAMES.items():
        layout = layout.replace(f"[tab {old}]", f"[tab {new}]").replace(f'qlinks "{old}"', f'qlinks "{new}"')
    left = re.findall(r"(?m)^\[tab (.+)\]", layout)
    long = [n for n in left if len(n) > 8]
    if long:
        sys.exit(f"make_port: tab names too long for the MPC's tab bar: {long}: add them to TAB_NAMES")
    return layout


def neat_qlinks(layout):
    """every page's Q-Link columns (4 at a time) as neat boxes: a row of controls inside one panel, in fours, the
    rest of a column left empty, so MPC's outline of the column in use doesn't spread over the page"""
    out = []
    for tab in re.split(r"(?m)^(?=\[tab )", layout):
        if not tab.startswith("[tab ") or tab.startswith("[tab OSC]"):
            out.append(tab)
            continue
        lines = tab.rstrip("\n").split("\n")
        frames, ctrls = [], []
        for ln in lines:
            f = re.match(r"frame x=(\d+) y=(\d+) w=(\d+) h=(\d+)", ln)
            if f:
                frames.append(tuple(map(int, f.groups())))
            m = re.match(r"\s*(knob|popup|toggle|button|stepper|readout) cx=(\d+) cy=(\d+).* key=(\S+)", ln)
            if m:
                cx, cy = int(m[2]), int(m[3]) - (20 if m[1] == "popup" else 0)
                fr = next((i for i, (x, y, w, h) in enumerate(frames) if x <= cx < x + w and y <= cy < y + h), -1)
                ctrls.append((fr, cy // 40, cx, m[4]))
        groups = {}
        for fr, row, cx, key in ctrls:
            groups.setdefault((fr, row), []).append((cx, key))
        chunks = []
        for g in sorted(groups, key=lambda g: (g[1], min(c[0] for c in groups[g]))):   # top to bottom, left to right
            ks = [k for _, k in sorted(groups[g])]
            chunks += [ks[i:i + 4] for i in range(0, len(ks), 4)]
        if len(chunks) <= 4:
            keys = [k for c in chunks for k in (c + ["-"] * 4)[:4]]
            while keys and keys[-1] == "-":
                keys.pop()
            lines = [ln if not ln.startswith("qlinks ") else re.sub(r"= .*", "= " + ",".join(keys), ln) for ln in lines]
        out.append("\n".join(lines) + "\n\n")
    return "".join(out)


def with_cells(layout):
    """every page's controls in the editor's cells (art/cells_<page>_<panel>.svg), each panel's drawn just after the
    panel (before the controls' own baked labels, which go on top). -> (layout, {file name: svg})"""
    out, files = [], {}
    for n, tab in enumerate(re.split(r"(?m)^(?=\[tab )", layout)):
        if not tab.startswith("[tab "):
            out.append(tab)
            continue
        lines = tab.rstrip("\n").split("\n")
        ctrls = []
        for ln in lines:
            m = re.match(r"\s*(knob|popup|toggle|button) cx=(\d+) cy=(\d+)", ln)
            if m and 'label=""' not in ln:              # (a panel's own BANK list sits in its head, no cell)
                ctrls.append((int(m[2]), int(m[3]) - (20 if m[1] == "popup" else 0)))
        res = []
        for ln in lines:
            res.append(ln)
            f = re.match(r"frame x=(\d+) y=(\d+) w=(\d+) h=(\d+)", ln)
            if not f:
                continue
            x, y, w, h = map(int, f.groups())
            boxes = [(cx - 70, cy - 52, 140, 152) for cx, cy in ctrls if x <= cx < x + w and y + 60 <= cy < y + h]
            if boxes:
                name = f"art/cells_{n}_{len([k for k in files if k.startswith(f'art/cells_{n}_')])}.svg"
                files[name] = cells_svg(boxes)
                res.append(f"art file={name}")
        out.append("\n".join(res) + "\n\n")
    return "".join(out), files


def osc_tab():
    """the OSC page: per oscillator its badge and name, its WAVETABLE box (the factory banks, then your files in
    data/Wavetables in folder order: arrows, the dial, or LIST for the whole list over the panel), the 3D view, the
    controls"""
    out, keys = ["[tab OSC]"], []
    for n in range(len(OSC)):                           # the panels first (the cells go on them)
        out.append(f'frame x={10 + n * 634} y=92 w=626 h=616 title=""')
    for n, (letter, wave, ctrls, banks) in enumerate(OSC):
        x, y, w, h = 10 + n * 634, 92, 626, 616
        out.append(f'art file=art/badge_{letter.lower()}.png x={x + 18} y={y + 15} w=30 h=30')
        out.append(f'text cx={x + 60} cy={y + 30} label="OSC {letter}" size=2.4 align=left color=e8ecef '
                   f'fontfile=fonts/BarlowSemiCondensed-Bold.ttf case=none')
        out.append(f'stepper cx={x + 330} cy={y + 30} w=320 h=44 label="" key=w{wave}wt tsize=20')
        out.append(f'button cx={x + w - 66} cy={y + 30} label="LIST" label_on="CLOSE" key=w{wave}list')
        vx, vy = x + (w - VIEW_W) // 2, y + 58
        out.append(f'art file=art/wt_user.png x={vx} y={vy} w={VIEW_W} h={VIEW_H}')
        out.append(f'meter cx={vx + VIEW_W // 2} cy={vy + VIEW_H // 2} w={VIEW_W} h={VIEW_H} key=w{wave}pos '
                   f'strip=art/wt{wave}_file.png frames=17 when=w{wave}shown:{banks + 1}')   # a file, drawn in 3D
        cw = VIEW_W // VIEW_COLS                        # a user table: its wave at WT POS, column by column
        for c in range(VIEW_COLS):
            out.append(f'meter cx={vx + c * cw + cw // 2} cy={vy + VIEW_H // 2} w={cw} h={VIEW_H} key=w{wave}c_{c + 1} '
                       f'strip=art/wtcol_{letter.lower()}.png frames=33 when=w{wave}shown:0')
        for b in range(banks):
            out.append(f'meter cx={vx + VIEW_W // 2} cy={vy + VIEW_H // 2} w={VIEW_W} h={VIEW_H} key=w{wave}pos '
                       f'strip=art/wt{wave}_{b}.png frames=17 when=w{wave}shown:{b + 1}')
        cols = [[f"w{wave}wt"], []]
        for i, c in enumerate(ctrls):
            if c is None:
                continue
            kind, key, label = c
            cx, cy = x + 88 + 150 * (i % 4), y + 318 + 160 * (i // 4)
            cols[i // 4].append(key)
            if kind == "knob":
                out.append(f'knob cx={cx} cy={cy} r=36 label="{label}" key={key} ns=17 vs=19 when=w{wave}list:0')
            else:
                out.append(f'popup cx={cx} cy={cy + 20} w=134 h=48 label="{label}" key={key} tsize=18 when=w{wave}list:0')
        keys += [k for col in cols for k in (col + ["-"] * 4)[:4]]
        out.append(f'list x={x + 18} y={y + 58} w={w - 36} h={LIST_ROWS * ROW_H} key=w{wave}row cols=1 rows={LIST_ROWS} '
                   f'th={ROW_H} gap=0 tsize=26 talign=left when=w{wave}list:1')
    out.append(f'qlinks "OSC" = {",".join(keys)}')
    return "\n".join(out) + "\n\n"


def main():
    check = "--check" in sys.argv
    GEN.mkdir(parents=True, exist_ok=True)
    run(sys.executable, "tools/gen_wavetables.py", GEN / "cr_wavetables.h")
    run(sys.executable, "tools/gen_presets.py", GEN / "cr_presets.h")
    run(sys.executable, "tools/gen_presets.py", "--keys", GEN / "cr_keys.h")
    exe = PORT / "build" / "gen_params"
    run(os.environ.get("CC", "cc"), "-O1", "-std=c99", "-Wall", "-Wextra", "-Werror", "-Isrc/core", "-Isrc/dsp",
        "-Isrc/host", f"-I{GEN}", f"-I{PORT}", PORT / "gen_params.c", "src/core/cr_patch.c", "src/core/cr_text.c",
        "src/core/cr_arp.c", "-o", exe)
    params = locked_order(run(exe))
    osc = osc_tab()
    with tempfile.TemporaryDirectory() as td:
        pj = Path(td) / "params.json"
        d = json.loads(params)                          # the auto-layout makes every page but the OSC one
        d["sections"] = [sec for sec in d["sections"] if sec["label"] not in OSC_SECTIONS]
        pj.write_text(json.dumps(d))
        auto = Path(td) / "layout.conf"
        run(sys.executable, MV / "tools" / "studio.py", "auto", pj, "-o", auto)
        names = {p["key"]: p["name"] for p in json.loads(params)["params"]}
        auto_tabs = re.split(r"(?m)^(?=\[tab )", auto.read_text())
        # the auto-layout's MORE page holds what no section names: the OSC page's controls and the hidden views
        auto_text = "".join(t for t in auto_tabs if not t.startswith("[tab MORE"))
        body, cells = with_cells(neat_qlinks(short_tabs(osc + bigger(auto_text, names))))
        layout = THEME + body
    stale = []
    if "--views" in sys.argv:                           # the 3D wavetable views' filmstrips (committed PNGs)
        run(sys.executable, PORT / "make_views.py", GEN / "cr_wavetables.h")
    for name, text in [("params.json", params), ("layout.conf", layout)] + sorted(cells.items()):
        f = PORT / name
        if f.exists() and f.read_text() == text:
            continue
        if check:
            stale.append(name)
        else:
            f.write_text(text)
            print(f"make_port: wrote ports/mpc/{name}")
    if stale:
        sys.exit(f"make_port: {', '.join(stale)} out of step with the engine: run python3 ports/mpc/make_port.py and commit")


if __name__ == "__main__":
    main()
